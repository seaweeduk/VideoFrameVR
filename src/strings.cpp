std::string languageName(int i) {
  if (i > 0 && i < languageCount()) return kLanguages[i - 1].text->languageName;
  return std::string(kEnglish.automaticLanguage) + " (" +
         kLanguages[automaticLanguage() - 1].text->languageName + ")";
}
void setLanguage(const std::string& code) {
  choice = findLanguage(code);
  language = kLanguages[(choice ? choice : automaticLanguage()) - 1].text;
  current = named(language, serverName);
}
void setServerName(const std::string& name) {
  serverName = name.empty() ? std::string(kServerName) : name;
  current = named(language, serverName);
}
const std::string& serverNameShown() { return serverName; }
const Strings& stashOwnStrings() { return *language.load(); }
const Strings& stringsNamed(const char* name) { return *named(language, name); }
const char* shownLanguageCode() {
  for (const Language& l : kLanguages)
    if (l.text == language) return l.code;
  return "en";
}

std::string viewpointText(int percent) {
  const ViewpointStrings& t = strings().viewpoint;
  if (percent == 0) return t.centered;
  char buf[96];
  std::snprintf(buf, sizeof(buf), percent > 0 ? t.closer : t.back, std::abs(percent));
  return buf;
}

std::string clockTime(double seconds) {
  const int total = static_cast<int>(std::max(0.0, seconds));
  char buf[32];
  if (total >= 3600)
    std::snprintf(buf, sizeof(buf), "%d:%02d:%02d", total / 3600, (total / 60) % 60, total % 60);
  else
    std::snprintf(buf, sizeof(buf), "%d:%02d", total / 60, total % 60);
  return buf;
}
